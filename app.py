import streamlit as st
from PIL import Image
import exifread
from transformers import pipeline
import io 

st.title("Free AI Image Detector")
st.write("Upload an image to check whether it has been generated by an AI tool")

@st.cache_resource
def load_detector():
    detector = pipeline("image-classification", model="dima806/ai_vs_real_image_detection")
    return detector

with st.spinner("Loading AI detection model..."):
    detector = load_detector()

file = st.file_uploader("Upload an image file", type = ["jpg", "jpeg", "png", "webp"])

if file is not None:
    image = Image.open(file)
    col1, col2 = st.columns([1, 1])

    with col1:
        st.image(image, caption = "Uploaded Image", use_container_width=True)

    with col2:
        st.subheader("Probability of AI Text")

        with st.spinner("Analyzing image..."):
            results = detector(image)
            
            scores = {res["label"]: res["score"] for res in results}
            ai_probability = scores.get("Fake", scores.get("AI-Generated", 0.0))

            if ai_probability>0.70:
                st.error(f"Likely AI Generated ({ai_probability * 100:.1f}% confidence)")
            elif ai_probability > 0.40:
                st.warning(f"Unsure ({ai_probability*100:.1f}%)")
            else:
                st.success(f"Likely Authentic Photo")
   

